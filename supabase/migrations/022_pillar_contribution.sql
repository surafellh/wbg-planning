-- 022: Pillar contribution. Shared by Demo and Live (it is strategy-level, like pillars and goals).
create table if not exists public.pillar_focus(unit_id uuid references org_units(id) on delete cascade, pillar_id uuid references group_pillars(id) on delete cascade, focus numeric not null default 0 check (focus>=0), source text default 'draft', primary key(unit_id, pillar_id));
create table if not exists public.unit_size(unit_id uuid primary key references org_units(id) on delete cascade, size numeric check (size>=0), basis text);
alter table public.pillar_focus enable row level security; alter table public.unit_size enable row level security;
create policy pillar_focus_r on public.pillar_focus for select to authenticated using (public.has_position());
create policy pillar_focus_w on public.pillar_focus for all to authenticated using (public.is_group_admin()) with check (public.is_group_admin());
create policy unit_size_r on public.unit_size for select to authenticated using (public.has_position());
create policy unit_size_w on public.unit_size for all to authenticated using (public.is_group_admin()) with check (public.is_group_admin());
